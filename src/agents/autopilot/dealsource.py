"""Where deals come from (build plan 6.5).

A closed deal used to leave nothing behind but its status. Which list it came off, which channel
reached the owner, how long it took and who did the work were all in people's memories, so the
budget was set by feel and the pay plan (a share to whoever generated the lead, whoever carried it
and whoever closed) had nothing to be paid from.

AT CLOSING. Each night the stage finds the records whose status changed to a closed status and
writes down, for each one:

    lane       the list family the record sits in (its tags and lists, read by lanes.lane_of)
    list       the list it came off, first to market lists first
    channel    the conversation that made it a lead: our call, their text, a call to a mail tracking
               line, or a call back on another line (which could be from a voicemail, a text or a letter)
    source     first pass, a Not Interested owner called again, an old lead worked again, or research
    days       from the first touch (dial, text or mail piece) to the closing
    three names   who generated the lead, who carried it, who closed, read from the call log

The names are a READING, not a ruling. The log says whose calls were answered when; it does not say
who earned what. They are shown with "confirm before paying on it", written to DataSift only into
an empty field, and never over a name a person typed.

EACH MONTH: deals by source, lane, list and channel; cost per deal; leads per 100 touches by
channel; mail response by piece.

What this cannot see, said in the report every time:
  * COST. The autopilot's own ledger holds what it paid: mail, skip traces, phone scoring and
    research. The dialer, the texting tool, salaries and subscriptions are not there unless the owner
    types them under inputs.monthly_costs in team/kpi.yaml.
  * TEXTS. Smarter Contact's messages are not in DataSift's log. The text touches are counted from
    the log AND from the autopilot's own text ledger (limits.py), but a reply to such a text is in
    neither, so a lead that began as a text reply can read as the lead manager's call. The channel is
    the last conversation the LOG holds.

The deal rows are the autopilot's own record and are kept in plan mode. The only change to the
account is the seven closing fields, behind ctx.write, each with its before-value in the change log.
"""
