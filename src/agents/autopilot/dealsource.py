# ---------------------------------------------------------------------- small reads, cached
def owner_of(ctx: Ctx, record_uuid: str, reads: dict) -> str:
    """The owner behind a record. Calls and texts are logged under the owner, status changes under
    the record, so every question about a lead needs this join. It is remembered, and a run opens at
    most `reads["left"]` records for it. When the hour's request budget runs out the reading stops
    and the report goes on with what it has: `reads["budget"]` says so."""
    known = ledger.fact(record_uuid, "owner_uuid")
    if known:
        return str(known)
    if reads.get("left", 0) <= 0:
        reads["skipped"] = reads.get("skipped", 0) + 1
        return ""
    reads["left"] -= 1
    try:
        rec = ctx.crm.record(record_uuid)
    except budget.BudgetExhausted:
        reads["left"], reads["budget"] = 0, True
        reads["skipped"] = reads.get("skipped", 0) + 1
        return ""
    except Exception:  # noqa: BLE001  (one unreadable record must not stop the table)
        return ""
    owner = (rec.get("owner") or {}).get("uuid") or ""
    if owner:
        ledger.set_fact(record_uuid, "owner_uuid", owner)
    return owner


def fee_of(ctx: Ctx, record_uuid: str, label: str) -> float:
    """What the deal paid, from the custom field the playbook names (fee_field), read once when the
    closing is recorded. 0 when the field is empty or cannot be read: the margin then says it has no
    figure, it never assumes one."""
    try:
        have = {str(k).strip().lower(): v for k, v in (ctx.crm.custom_fields(record_uuid) or {}).items()}
    except Exception:  # noqa: BLE001  (a fee that cannot be read is no fee; the closing itself is still recorded)
        return 0.0
    kept = "".join(ch for ch in str(have.get(label.strip().lower()) or "") if ch.isdigit() or ch == ".")
    try:
        return float(kept) if kept else 0.0
    except ValueError:
        return 0.0


def tracking_lines(st) -> dict:
    """number -> piece ("" when the line is shared by every piece), from the stage's mail_tracking_lines."""
    raw = st.get("mail_tracking_lines") or {}
    if isinstance(raw, (list, tuple)):
        raw = {n: "" for n in raw}
    return {gate.digits(n): str(p or "") for n, p in raw.items() if gate.digits(n)}


# ---------------------------------------------------------------------- one lead, one deal
def lead_moments(record_uuid: str, until: datetime | None = None) -> list[datetime]:
    """Every time the record entered a lead status from outside one, oldest first. More than one
    means an old lead that was worked again."""
    out = []
    for e in activity.events("property.status.updated", resource=record_uuid, until=until):
        to = str(e["data"].get("to") or "").strip().lower()
        frm = str(e["data"].get("from") or "").strip().lower()
        if to in lanes.LEAD_STATUSES and frm not in lanes.LEAD_STATUSES:
            out.append(e["when"])
    return out


def origin(cat: kpi.Catalog, owner_uuid: str, lead_at: datetime | None, tracking: dict | None = None) -> dict:
    """The conversation that made the lead: the last one the log holds with this owner before the
    status changed. How far back that conversation may be, and how long after a call a status may
    still be set, are part of the catalog's definition of an opportunity (a status is often set a
    few minutes after the call ends). {"channel", "caller", "when"}; channel is "" when the log holds
    no conversation there."""
    blank = {"channel": "", "caller": "", "when": None}
    if not owner_uuid or lead_at is None:
        return blank
    tracking = tracking or {}
    rule = cat.definition("opportunity")
    since = lead_at - timedelta(days=float(rule["credit_days"]))
    until = lead_at + timedelta(minutes=float(rule["settle_minutes"]))
    evs = kpi.conversation_events(cat, since=since, until=until, owner=owner_uuid)
    if not evs:
        # A call too short to count as a conversation still says who was on the phone.
        short = [e for e in activity.events("owner.call.answered", resource=owner_uuid, since=since, until=until)
                 if e["data"].get("direction") != "inbound"]
        if short:
            return {"channel": "call", "caller": str(short[-1]["data"].get("caller") or "").strip(), "when": short[-1]["when"]}
        return blank
    ev = evs[-1]
    channel = ev["kind"]
    if channel == "call back" and (ev["line"] in tracking or ev["number"] in tracking):
        channel = "mail"
    return {"channel": channel, "caller": ev["caller"], "when": ev["when"], "line": ev["line"], "number": ev["number"]}


def source_of(record_uuid: str, lead_at: datetime | None, earlier_leads: int, researched_tags) -> str:
    """How the record came to be a lead, from what it had been before: researched, a Not Interested
    owner called again, an old lead worked again, a record whose call round had ended, or first pass."""
    if lead_at is None:
        return ""
    want = {str(t).lower() for t in researched_tags or []}
    for e in activity.events("property.tags.added", resource=record_uuid, until=lead_at):
        if want & {str(t).lower() for t in e["data"].get("tags") or []}:
            return "research"
    before = [str(e["data"].get("to") or "").strip().lower()
              for e in activity.events("property.status.updated", resource=record_uuid, until=lead_at)]
    if "not_interested" in before:
        return "not interested follow-up"
    if earlier_leads:
        return "an old lead worked again"
    if "exhausted" in before:
        return "after the call round ended"
    return "first pass"


def first_touch(owner_uuid: str, record_uuid: str) -> tuple[datetime | None, bool]:
    """(our first dial, text or mail piece to this owner, whether the real first touch may be older
    than the log). The second value is true when the first dial sits at the very start of the log
    copy: then the count of days is a floor."""
    found = []
    for e in activity.events(activity.DIAL, resource=owner_uuid, limit=20):
        if e["data"].get("direction") != "inbound":
            found.append(e["when"])
            break
    for e in activity.events(("owner.sms.sent", "owner.sms.delivered"), resource=owner_uuid, limit=1):
        found.append(e["when"])
    for e in ledger.events(record_uuid, "mail")[:1]:
        found.append(datetime.fromisoformat(e["at"]))
    if not found:
        return None, False
    first = min(found)
    reach = kpi.log_reach(activity.DIAL)
    return first, bool(reach and first - reach < timedelta(days=1))


def who(owner_uuid: str, since: datetime | None, until: datetime | None) -> tuple[str, str]:
    """(who carried the lead, who closed it) from the answered calls between two moments: the caller
    on the most of them, and the caller on the last one."""
    calls = [str(e["data"].get("caller") or "").strip()
             for e in activity.events("owner.call.answered", resource=owner_uuid, since=since, until=until)
             if e["data"].get("direction") != "inbound"]
    calls = [c for c in calls if c]
    if not calls:
        return "", ""
    count = Counter(calls)
    top = max(count.values())
    carried = [c for c in reversed(calls) if count[c] == top][0]
    return carried, calls[-1]


def describe(ctx: Ctx, cat: kpi.Catalog, rec: dict, closed_at: datetime) -> dict:
    """Everything recorded about one closed deal, from its record and the stored log."""
    st = ctx.stage
    u = rec.get("uuid") or ""
    owner = (rec.get("owner") or {}).get("uuid") or ""
    if owner:
        ledger.set_fact(u, "owner_uuid", owner)
    # The lane is read with the status set aside: a closed deal's status says where it ended, and
    # its tags and lists still say which list family it came off.
    lane = lanes.lane_of(dict(rec, status=None), getattr(ctx.policy, "lanes", None))
    titles = [str(t.get("title") or t.get("name") or "") if isinstance(t, dict) else str(t) for t in rec.get("lists") or []]
    ignore = {str(x).lower() for x in st.get("ignore_lists") or []}
    titles = [t for t in titles if t and t.lower() not in ignore]
    order = [str(x) for x in (st.get("list_order") or LIST_ORDER)]
    low = {t.lower(): t for t in titles}
    primary = next((low[o.lower()] for o in order if o.lower() in low), sorted(titles)[0] if titles else "")
    moments = lead_moments(u, until=closed_at)
    lead_at = moments[-1] if moments else None
    org = origin(cat, owner, lead_at, tracking_lines(st))
    contract = [e["when"] for e in activity.events("property.status.updated", resource=u, until=closed_at)
                if str(e["data"].get("to") or "").strip().lower() in {str(s).lower() for s in st.get("contract_statuses") or ["under_contract"]}]
    contract_at = contract[-1] if contract else None
    carried, closed_by = who(owner, lead_at or closed_at - timedelta(days=int(st.get("carry_days", 120))),
                             contract_at or closed_at) if owner else ("", "")
    first, floor = first_touch(owner, u) if owner else (None, False)
    days = (closed_at - first).days if first else None
    return {"record_uuid": u, "closed_at": closed_at.isoformat(timespec="seconds"),
            "closed_day": kpi.local_day(closed_at, ctx.policy.tz), "street": addr(rec),
            "lane": LANE_WORDS.get(lane, lane), "list": primary, "channel": org["channel"],
            "source": source_of(u, lead_at, len(moments) - 1 if moments else 0, st.get("researched_tags") or ["Deep Prospected"]),
            "days": days, "generated_by": org["caller"], "carried_by": carried, "closed_by": closed_by,
            "detail": {"lists": titles[:8], "lead_at": lead_at.isoformat(timespec="seconds") if lead_at else "",
                       "contract_at": contract_at.isoformat(timespec="seconds") if contract_at else "",
                       "first_touch": first.isoformat(timespec="seconds") if first else "", "days_is_a_floor": floor}}


# ---------------------------------------------------------------------- the deal table
def save(deal: dict) -> None:
    kpi.ensure("ap_deals", SCHEMA)
    with store._LOCK, store._db() as c:
        c.execute("INSERT INTO ap_deals (record_uuid, closed_at, closed_day, street, lane, list, channel, source, days, "
                  "generated_by, carried_by, closed_by, detail, written, at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?) "
                  "ON CONFLICT(record_uuid) DO UPDATE SET closed_at=excluded.closed_at, closed_day=excluded.closed_day, "
                  "street=excluded.street, lane=excluded.lane, list=excluded.list, channel=excluded.channel, "
                  "source=excluded.source, days=excluded.days, generated_by=excluded.generated_by, "
                  "carried_by=excluded.carried_by, closed_by=excluded.closed_by, detail=excluded.detail, at=excluded.at",
                  (deal["record_uuid"], deal["closed_at"], deal["closed_day"], deal["street"], deal["lane"], deal["list"],
                   deal["channel"], deal["source"], deal["days"], deal["generated_by"], deal["carried_by"], deal["closed_by"],
                   json.dumps(deal.get("detail") or {}, default=str), json.dumps(deal.get("written") or {}), store.now()))


def deals(since_day: str = "", until_day: str = "") -> list[dict]:
    """Recorded deals, oldest first; days are business-local, `until_day` not included."""
    kpi.ensure("ap_deals", SCHEMA)
    q, args = "SELECT * FROM ap_deals WHERE 1=1", []
    if since_day:
        q += " AND closed_day>=?"
        args.append(since_day)
    if until_day:
        q += " AND closed_day<?"
        args.append(until_day)
    out = []
    with store._LOCK, store._db() as c:
        for r in c.execute(q + " ORDER BY closed_at, record_uuid", args).fetchall():
            d = dict(r)
            for k in ("detail", "written"):
                try:
                    d[k] = json.loads(d.get(k) or "{}")
                except ValueError:
                    d[k] = {}
            out.append(d)
    return out


def _set_written(record_uuid: str, written: dict) -> None:
    with store._LOCK, store._db() as c:
        c.execute("UPDATE ap_deals SET written=? WHERE record_uuid=?", (json.dumps(written), record_uuid))


def deal_line(d: dict) -> str:
    """One closed deal in a plain line, with the three names marked as a reading to confirm."""
    days = "" if d["days"] is None else ", %s%d days from the first touch" % (
        "at least " if (d.get("detail") or {}).get("days_is_a_floor") else "", d["days"])
    if any(d[k] for k in ("generated_by", "carried_by", "closed_by")):
        names = "Generated by %s, carried by %s, closed by %s (read from the call log: confirm before paying on it)." % tuple(
            d[k] or "nobody the log names" for k in ("generated_by", "carried_by", "closed_by"))
    else:
        names = "The call log names nobody on this deal: who generated, carried and closed it has to be filled in by hand."
    return "%s closed: %s%s%s%s. %s" % (
        d["street"], d["lane"], (", %s list" % d["list"]) if d["list"] else "",
        (", by %s" % d["channel"]) if d["channel"] else ", channel not in the log", days, names)


# ---------------------------------------------------------------------- the closing fields (the one write)
def write_fields(ctx: Ctx, deal: dict, labels: dict, missing: set) -> int:
    """Fill the deal's closing fields on its record. A field that does not exist is reported, an
    unknown value is never written, and a field that already holds something is left alone: it is
    either ours from an earlier run or a person's correction, and a person outranks the log."""
    u = deal["record_uuid"]
    state = deal.get("written") or {}
    done = set(state.get("written") or []) | set(state.get("kept") or [])
    wanted = {k: (labels[k], deal[k]) for k in FIELDS if k not in done and deal.get(k) not in (None, "")}
    ready = {}
    for k, (label, value) in wanted.items():
        fid = ctx.crm.custom_field_uuid(label)
        if fid:
            ready[k] = (label, fid, value)
        else:
            missing.add(label)
    if not ready:
        return 0
    have = {str(k).strip().lower(): v for k, v in (ctx.crm.custom_fields(u) or {}).items()}
    written, kept, n = list(state.get("written") or []), list(state.get("kept") or []), 0
    for k, (label, fid, value) in ready.items():
        current = have.get(label.strip().lower())
        if current not in (None, ""):
            kept.append(k)
            if str(current).strip() != str(value):
                ctx.out.tally["closing fields left as a person set them"] += 1
            continue
        ctx.change(u, "custom_field", {"label": label, "field_uuid": fid, "value": ""},
                   {"label": label, "field_uuid": fid, "value": str(value)})
        ctx.write("closing field", ctx.crm.set_custom_field, u, fid, str(value))
        n += 1
        if ctx.live:
            written.append(k)
    state = {"written": written, "kept": kept}
    if state != (deal.get("written") or {}):
        _set_written(u, state)
        deal["written"] = state
    if ctx.live and n:
        ledger.event(ctx.run_id, ctx.stage.id, u, "deal_source", {"fields": [labels[k] for k in written]},
                     now=ctx.now, tz=ctx.policy.tz)
    return n


# ---------------------------------------------------------------------- the monthly table
def _month(now: datetime, tz: str, back: int = 1) -> tuple[date, date]:
    """(first day, first day of the next month) for the calendar month `back` months before now."""
    d = now.astimezone(kpi.zone(tz)).date().replace(day=1)
    for _ in range(back):
        d = (d - timedelta(days=1)).replace(day=1)
    nxt = (d + timedelta(days=32)).replace(day=1)
    return d, nxt


def ledger_between(action: str, start: datetime, end: datetime) -> list[dict]:
    """The ledger's events of one kind between two moments. The ledger compares times as text, which
    is only right when both sides are written in the same zone, so the query is asked a day wide in
    UTC and the rows are then compared as real times. Without that a month's edge slips by the
    business zone's offset and a piece mailed on the last evening lands in the wrong month."""
    rows = ledger.events(action=action, since=(start - timedelta(days=1)).astimezone(timezone.utc))
    return [e for e in rows if start <= datetime.fromisoformat(e["at"]) < end]


def texts_sent(first: date, nxt: date) -> int | None:
    """Texts the autopilot released in a month, from its text ledger (limits.py). Those messages never
    reach DataSift's log, so without the ledger the text channel reads as empty. Counted the ledger's
    own way: a batch staged and never released is not a text, and a counter rise the autopilot did not
    make is left out, because the other system's sends may already be in the log. None when the ledger
    cannot be read: it belongs to another part of the autopilot, so this never stops the table."""
    try:
        from . import limits
        return sum(1 for r in limits.rows(since_day=first.isoformat(), until_day=nxt.isoformat(), statuses=("released",))
                   if r.get("system") != limits.OTHER)
    except Exception:  # noqa: BLE001
        log.exception("the text ledger could not be read")
        return None


def spend(start: date, end: date) -> dict:
    """What the autopilot itself paid in the window, by channel, from its own ledger. Mail is the
    mail lane; data is skip traces and phone scoring; research is the deep prospect's spend."""
    out = {"mail": 0.0, "data": 0.0, "research": 0.0}
    d = start
    while d < end:
        day = d.isoformat()
        out["mail"] += ledger.spent(day_=day, action="mail")
        out["data"] += ledger.spent(day_=day, exclude_action="mail")
        out["research"] += store.spent(day=day, research=True)
        d += timedelta(days=1)
    return {k: round(v, 2) for k, v in out.items()}


def mail_response(ctx: Ctx, cat: kpi.Catalog, start: datetime, end: datetime, reads: dict) -> dict | None:
    """piece -> {"pieces", "calls"} for the month, from calls that came in on a mail tracking line.
    A line set up for one piece names it; on a shared line the piece is the last one mailed to that
    owner before the call. None when no tracking line is set: then a letter's call back cannot be
    told from any other inbound call."""
    lines = tracking_lines(ctx.stage)
    if not lines:
        return None
    out: dict[str, dict] = {}
    for e in ledger_between("mail", start, end):
        out.setdefault(str(e["detail"].get("piece") or "piece"), {"pieces": 0, "calls": 0})["pieces"] += 1
    seen = set()
    for ev in activity.events(("owner.call.received", "owner.call.answered", "owner.call.missed"), since=start, until=end):
        d = ev["data"]
        hit = d.get("line") if d.get("line") in lines else d.get("number") if d.get("number") in lines else ""
        if not hit or (ev["event_type"] == "owner.call.answered" and d.get("direction") != "inbound"):
            continue
        if ev["resource"] in seen:
            continue                         # one owner calling three times is one response
        seen.add(ev["resource"])
        piece = lines[hit]
        if not piece and reads.get("left", 0) > 0:
            reads["left"] -= 1
            try:
                mailed = [m for r in ctx.crm.owner_records(ev["resource"], cap=10) for m in ledger.events(r["uuid"], "mail")
                          if datetime.fromisoformat(m["at"]) <= ev["when"]]
            except budget.BudgetExhausted:
                reads["left"], reads["budget"] = 0, True
                mailed = []
            except Exception:  # noqa: BLE001
                mailed = []
            if mailed:
                piece = str(max(mailed, key=lambda m: m["at"])["detail"].get("piece") or "")
        out.setdefault(piece or "a piece the ledger cannot name", {"pieces": 0, "calls": 0})["calls"] += 1
    return out


def month_table(ctx: Ctx, cat: kpi.Catalog, first: date, nxt: date) -> dict:
    tz = ctx.policy.tz
    start, end = kpi.day_start(first, tz), kpi.day_start(nxt, tz)
    rows = deals(since_day=first.isoformat(), until_day=nxt.isoformat())
    reads = {"left": int(ctx.stage.get("max_lead_reads", 60))}
    tracking = tracking_lines(ctx.stage)
    leads = kpi.new_leads(since=start, until=end)
    by_channel: Counter = Counter()
    for lead in leads:
        owner = owner_of(ctx, lead["record"], reads)
        by_channel[origin(cat, owner, lead["when"], tracking)["channel"] or "not in the log"] += 1
    paid = spend(first, nxt)
    typed = cat.monthly_costs()
    mail_pieces = len(ledger_between("mail", start, end))
    texts = len(activity.events(("owner.sms.sent",), since=start, until=end))
    from_ledger = texts_sent(first, nxt)
    days = sorted(r["days"] for r in rows if r["days"] is not None)
    return {"month": first.strftime("%B %Y"), "deals": len(rows),
            "by_source": dict(Counter(r["source"] or "not in the log" for r in rows)),
            "by_lane": dict(Counter(r["lane"] or "no lane" for r in rows)),
            "by_list": dict(Counter(r["list"] or "no list" for r in rows)),
            "by_channel": dict(Counter(r["channel"] or "not in the log" for r in rows)),
            "median_days": statistics.median(days) if days else None,
            "spend": paid, "typed_costs": typed, "total_cost": round(sum(paid.values()) + sum(typed.values()), 2),
            "touches": {"call": kpi.dials(since=start, until=end), "mail": mail_pieces, "text": texts + (from_ledger or 0)},
            "text_ledger": from_ledger,
            "leads": len(leads), "leads_by_channel": dict(by_channel), "leads_not_placed": reads.get("skipped", 0),
            "mail_response": mail_response(ctx, cat, start, end, reads), "budget_ran_out": bool(reads.get("budget")),
            "records": [{k: r[k] for k in ("record_uuid", "closed_day", "street", "lane", "list", "channel", "source", "days",
                                           "generated_by", "carried_by", "closed_by")} for r in rows]}


def _mix(counts: dict) -> str:
    return ", ".join("%d %s" % (n, k) for k, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))


def table_lines(cat: kpi.Catalog, t: dict) -> list[str]:
    """The monthly table as plain lines, most important first (the channel shows the first six)."""
    out = []
    if t["deals"]:
        out.append("%s: %d deal(s) closed. By source: %s. By lane: %s." % (t["month"], t["deals"], _mix(t["by_source"]), _mix(t["by_lane"])))
        ni = t["by_source"].get("not interested follow-up", 0)
        out.append("By channel: %s. By list: %s.%s Not Interested follow-up is %d%% of the deals (the catalog says %s)." % (
            _mix(t["by_channel"]), _mix(t["by_list"]),
            (" Median %d days from the first touch." % round(t["median_days"])) if t["median_days"] is not None else "",
            round(100.0 * ni / t["deals"]), cat.text("source.not_interested_share_of_deals")))
    else:
        out.append("%s: no deal closed." % t["month"])
    paid = t["spend"]
    parts = "mail %s, skip trace and scoring %s, research %s" % (kpi.money(paid["mail"]), kpi.money(paid["data"]), kpi.money(paid["research"]))
    typed = (", plus %s a month typed in (%s)" % (kpi.money(sum(t["typed_costs"].values())), ", ".join(sorted(t["typed_costs"])))) if t["typed_costs"] else ""
    if t["deals"]:
        out.append("Cost per deal: %s (%s spent: %s%s). The catalog says %s." % (
            kpi.money(t["total_cost"] / t["deals"]), kpi.money(t["total_cost"]), parts, typed, cat.text("owner.cost_per_deal")))
    else:
        out.append("Spent %s (%s%s) with no deal to set it against." % (kpi.money(t["total_cost"]), parts, typed))
    unseen = [n for n in ("dialer", "texting", "salaries", "subscriptions") if n not in t["typed_costs"]]
    if unseen:
        out.append("Not in that cost: %s. The ledger holds only what the autopilot paid; type the rest under "
                   "inputs.monthly_costs in team/kpi.yaml." % ", ".join(unseen))
    per = []
    for ch, label, unit in (("call", "calls", "dials"), ("mail", "mail", "pieces"), ("text", "texts", "texts")):
        touches, got = t["touches"][ch], t["leads_by_channel"].get(ch, 0)
        from_ledger = (t.get("text_ledger") or 0) if ch == "text" else 0
        if ch == "text" and not touches:
            per.append("texts are not in DataSift's log" if t.get("text_ledger") is None
                       else "no text in DataSift's log or in the autopilot's text ledger")
        elif touches:
            per.append("%s %s (%d lead(s) on %s %s%s)" % (label, kpi.num(round(100.0 * got / touches, 2)), got, kpi.num(touches), unit,
                                                          (", %s from the autopilot's text ledger" % kpi.num(from_ledger)) if from_ledger else ""))
    other = {k: n for k, n in t["leads_by_channel"].items() if k not in ("call", "mail", "text")}
    out.append("Leads per 100 touches: %s. %d new lead(s) in all%s. The catalog says %s." % (
        "; ".join(per) or "no touch is in the log", t["leads"], (", of them %s" % _mix(other)) if other else "",
        cat.text("channel.leads_per_100_touches")))
    mr = t["mail_response"]
    if mr is None:
        out.append("Mail response by piece: no tracking line is set (mail_tracking_lines), so a call back from a letter "
                   "cannot be told from any other call.")
    elif mr:
        out.append("Mail response by piece: %s." % "; ".join(
            "%s %d call(s) on %s piece(s)%s" % (k.replace("_", " "), v["calls"], kpi.num(v["pieces"]),
                                               (" (%s%%)" % kpi.num(round(100.0 * v["calls"] / v["pieces"], 1))) if v["pieces"] else "")
            for k, v in sorted(mr.items())))
    else:
        out.append("Mail response by piece: no piece went out and no call came in on a tracking line.")
    out.append(cat.footnote(USES))
    return out


# ---------------------------------------------------------------------- the stage
def run_dealsource(ctx: Ctx) -> None:
    st = ctx.stage
    cat = kpi.for_stage(ctx)
    if cat is None:
        return
    kpi.ensure("ap_deals", SCHEMA)
    kpi.sync_log(ctx, ("state", "calls", "texts"))
    tz = ctx.policy.tz
    closed = [str(s) for s in (st.get("closed_statuses") or ["closed"])]
    labels = dict(FIELDS)
    labels.update({k: str(v) for k, v in (st.get("fields") or {}).items() if k in FIELDS})

    # --- closings the table does not hold yet
    known = {d["record_uuid"]: d for d in deals(since_day=(ctx.now - timedelta(days=int(st.get("write_days", 45)) + 2)).date().isoformat())}
    have = {d["record_uuid"] for d in deals()}
    events = [e for e in kpi.status_changes(closed, since=ctx.now - timedelta(days=int(st.get("scan_days", 45))), until=ctx.now)
              if e["record"] not in have]
    cap = int(st.get("max_records", 25))
    new = []
    for e in events[:cap]:
        try:
            rec = ctx.crm.record(e["record"])
        except budget.BudgetExhausted as exc:
            ctx.out.problem("stopped reading closings: %s. The rest are read next run" % exc)
            break
        except Exception as exc:  # noqa: BLE001
            ctx.out.problem("could not read a closed record (%s); it is tried again next run" % str(exc)[:100])
            continue
        if not rec.get("uuid"):
            continue
        deal = describe(ctx, cat, rec, e["when"])
        if st.get("fee_field"):
            deal["detail"]["fee"] = fee_of(ctx, deal["record_uuid"], str(st.get("fee_field")))
        save(deal)
        known[deal["record_uuid"]] = dict(deal, written={})
        new.append(deal)
    if len(events) > cap:
        ctx.out.tally["closings left for the next run (%d a run)" % cap] = len(events) - cap
    ctx.out.found = len(events)

    # --- the closing fields, for every recent deal that still has one to fill
    missing: set = set()
    wrote = on = 0
    if st.get("write_fields", True):
        for deal in known.values():
            n = write_fields(ctx, deal, labels, missing)
            wrote += n
            on += 1 if n else 0
    if wrote:
        ctx.out.tally["closing fields %s" % ("written" if ctx.live else "to write")] = wrote
    ctx.out.acted = len(new)

    # --- the monthly table, once, on the first run of a new month
    first, nxt = _month(ctx.now, tz, back=1)
    mode = str(st.get("table") or "monthly")
    due = mode == "always" or (mode != "off" and store.kv_get(KV_TABLE) != first.strftime("%Y-%m"))
    table = None
    if due:
        table = month_table(ctx, cat, first, nxt)
        for ln in table_lines(cat, table):
            ctx.out.line(ln)
        kpi.save_report("deal_sources_%s" % first.strftime("%Y-%m"), ctx.now, table)
        # Only a run the queue started marks the month as reported: a look from the command line
        # must not use up the one table the channel gets.
        if ctx.task_id:
            store.kv_set(KV_TABLE, first.strftime("%Y-%m"))
        ctx.out.acted += 1                    # the table is a report: it posts even in a month with no deal
        if table["leads_not_placed"]:
            ctx.out.tally["new leads whose channel was not read (read cap)"] = table["leads_not_placed"]
        if table["budget_ran_out"]:
            ctx.out.problem("the hour's request budget ran out while placing leads by channel, so the leads-per-touch line is short")
    for deal in new:                          # after the table: the channel shows only the first lines
        ctx.out.line(deal_line(deal))
    if missing:
        text = ("%d closing field(s) do not exist in DataSift yet (%s). Create them as text fields and the next run "
                "fills them." % (len(missing), ", ".join(sorted(missing))))
        # Said when there is news to hang it on (a closing, the monthly table), not every night for
        # the six weeks a deal stays in the write window.
        if new or table is not None:
            ctx.out.problem(text)
        else:
            ctx.out.tally["closing fields that do not exist in DataSift yet"] = len(missing)

    verb = "Wrote" if ctx.live else "Would write"
    fields = "%s %d closing field(s) on %d record(s)." % (verb, wrote, on) if wrote else ""
    if table is not None:
        ctx.out.head = ("Where deals came from in %s: %d deal(s), %s spent. %s" % (
            table["month"], table["deals"], kpi.money(table["total_cost"]), fields)).strip()
    elif new:
        ctx.out.head = ("%d deal(s) closed since the last check, each recorded with its source. %s" % (len(new), fields)).strip()
    elif wrote:
        ctx.out.head = "No new closing. %s" % fields
    else:
        ctx.out.head = "No deal closed since the last check."
