def call(i, owner, when, kind="made", seconds=0, caller="Adriana", number="8655550101", inbound=False,
         recording=True, line="8655550000", source="kixie"):
    c = {"destination_number": line if inbound else number, "origin_number": number if inbound else line,
         "direction": "inbound" if inbound else "outbound", "duration": seconds, "source": source, "owner": owner,
         "uuid": "c-%s" % i, "extra": {}, "user": {"first_name": caller, "uuid": "u-%s" % caller.lower()} if caller else None,
         "recording": ("https://%s/%s.mp3" % (RECORDINGS, i)) if recording and kind != "made" else ""}
    return {"id": "kc-%s" % i, "event_type": "owner.call.%s" % kind, "resource": owner, "resource_type": "owner",
            "source": source, "author": "system", "timestamp": _ts(when), "payload": {"call": c}}


