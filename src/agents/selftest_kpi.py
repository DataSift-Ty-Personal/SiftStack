class KCRM(FakeCRM):
    """The autopilot selftest's fake DataSift, counting what a measurement stage reads."""

    budget_after = None        # set to N: the N+1th record read finds the hour's request budget spent

    def __init__(self, records, **kw):
        super().__init__(records, **kw)
        self.record_reads: list = []
        self.musts: list = []
        self.fields = dict(FakeCRM.fields)

    def record(self, u):
        if self.budget_after is not None and len(self.record_reads) >= self.budget_after:
            from .autopilot import budget
            raise budget.BudgetExhausted("this app's share of the hour is used")
        self.record_reads.append(u)
        return super().record(u)

    def search(self, must, limit=250, offset=0):
        self.musts.append(copy.deepcopy(must))
        return super().search(must, limit, offset)

    def set_custom_field(self, u, field_uuid, value):
        super().set_custom_field(u, field_uuid, value)
        label = next((k for k, v in self.fields.items() if v == field_uuid), field_uuid)
        self.custom.setdefault(u, {})[label] = value


