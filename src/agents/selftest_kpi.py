def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(check, tmp: Path) -> None:
    from . import store
    from .autopilot import (activity, alarms, cadence, capture, coachpick, dealsource, goals, kpi, lanes, ledger, pacing,
                            policy, registry, researchstats, stages, sweep)
    saved_cfg = (config.DATA_DIR, config.MODE, config.TEAM_DIR)
    saved_presets = dict(PRESETS)
    config.DATA_DIR, config.MODE = tmp, "dry"
    store.init()
    PRESETS["Hottest - 02 Ready to Call"] = lambda r: "Priority 1" in r["tags"] and r["owner"]["phones"] and r["predictivecall_attempts"] == 0

    # The orchestrator adds one line per kind to registry.EXTRA. Until it has, stand the same lines
    # in for the length of this section, exactly as policy and sweep read them at import.
    added = [k for k in REGISTRY_LINES if k not in registry.EXTRA]
    saved_pol = (policy.KINDS, policy.NO_PRESETS, sweep.REPORT_KINDS)
    for k in added:
        registry.EXTRA[k] = REGISTRY_LINES[k]
        policy.SPEND_BY_KIND[k] = REGISTRY_LINES[k][2]
    policy.KINDS = tuple(dict.fromkeys(policy.KINDS + tuple(added)))
    policy.NO_PRESETS = tuple(dict.fromkeys(policy.NO_PRESETS + tuple(k for k in added if not REGISTRY_LINES[k][3])))
    sweep.REPORT_KINDS = set(sweep.REPORT_KINDS) | {k for k in added if REGISTRY_LINES[k][4]}

    K.store, K.activity, K.alarms, K.cadence, K.capture, K.coachpick = store, activity, alarms, cadence, capture, coachpick
    K.dealsource, K.goals, K.kpi, K.lanes, K.ledger, K.pacing, K.policy = dealsource, goals, kpi, lanes, ledger, pacing, policy
    K.registry, K.researchstats, K.stages, K.sweep, K.tmp = registry, researchstats, stages, sweep, tmp
    K.blocks = yaml.safe_load("stages:" + STAGE_BLOCKS)["stages"]
    K.shipped = yaml.safe_load(kpi.path().read_text(encoding="utf-8"))
    K.team_files = {f: _sha(f) for f in (config.TEAM_DIR / "kpi.yaml",) if f.is_file()}

    from .autopilot import limits
    limits.ensure()                     # the text ledger is read by the deal-source table; it must exist to be put back
    shared = ("ap_log", "ap_capture", "ap_facts", "ap_events", "ap_changes", "ap_owner_lane", "ap_batches", "ap_texts")

    def fresh() -> None:
        with store._LOCK, store._db() as c:
            for table in shared + ("ap_alarms", "ap_deals", "ap_coach_picks", "ap_research_checks"):
                try:
                    c.execute("DELETE FROM " + table)
                except sqlite3.OperationalError:
                    pass                                    # one of this track's tables, not created yet
            c.execute("DELETE FROM kv WHERE key LIKE 'autopilot:%'")
            c.execute("DELETE FROM spend WHERE what LIKE 'kpi selftest%'")

    def snapshot() -> dict:
        """What the shared tables hold before this section empties them, so it can put them back:
        the section after this one finds the database as the section before left it."""
        with store._LOCK, store._db() as c:
            snap = {t: [tuple(r) for r in c.execute("SELECT * FROM " + t).fetchall()] for t in shared}
            snap["kv"] = [tuple(r) for r in c.execute("SELECT * FROM kv WHERE key LIKE 'autopilot:%'").fetchall()]
        return snap

    def restore(snap: dict) -> None:
        with store._LOCK, store._db() as c:
            for t in shared:
                c.execute("DELETE FROM " + t)
                for row in snap[t]:
                    c.execute("INSERT INTO %s VALUES (%s)" % (t, ",".join("?" * len(row))), row)
            c.execute("DELETE FROM kv WHERE key LIKE 'autopilot:%'")
            for row in snap["kv"]:
                c.execute("INSERT INTO kv VALUES (%s)" % ",".join("?" * len(row)), row)
            c.execute("DELETE FROM tasks WHERE record_uuid='kpi-selftest-record'")

    def put(rows) -> None:
        activity._store(list(rows))

    def cat(figures=None, inputs=None, drop=(), definitions=None, pacing_block=None):
        """The shipped catalog with a few values changed, parsed the way the file is."""
        data = copy.deepcopy(K.shipped)
        for key, v in (figures or {}).items():
            f = data["figures"][key]
            for old in ("value", "low", "high"):
                f.pop(old, None)
            if isinstance(v, tuple):
                f["low"], f["high"] = v
            else:
                f["value"] = v
        for key in drop:
            data["figures"].pop(key)
        if inputs:
            data["inputs"].update(inputs)
        for name, d in (definitions or {}).items():
            data["definitions"][name].update(d)
        if pacing_block:
            data["pacing"].update(pacing_block)
        return kpi.parse(data)

    def pol(overrides=None, extra=None, base_overrides=None):
        data = copy.deepcopy(BASE)
        data["stages"].update(copy.deepcopy(K.blocks))
        for sid, changes in (base_overrides or {}).items():
            data["stages"][sid].update(changes)
        for sid, changes in (overrides or {}).items():
            data["stages"][sid].update(changes)
        data["stages"].update(copy.deepcopy(extra or {}))
        return policy.parse(data, EMPLOYEES)

    def go(stage_id, crm, now, p=None, task=None, plan=False, enqueue=None):
        return sweep.run(stage_id, task, plan=plan, crm=crm, now=now.astimezone(timezone.utc), pol=p or pol(), enqueue=enqueue)

    def ctx_for(stage_id, crm, now, p=None, live=False):
        p = p or pol()
        st = p.stage(stage_id)
        out = stages.Summary(stage=st.id, kind=st.kind, owner=st.owner, mode=st.mode, live=live)
        return stages.Ctx(policy=p, stage=st, crm=crm, run_id="kpi-test", now=now.astimezone(timezone.utc), live=live, out=out)

    K.fresh, K.put, K.cat, K.pol, K.go, K.ctx_for = fresh, put, cat, pol, go, ctx_for
    before = snapshot()
    try:
        fresh()
        _catalog(check)
        _counting(check)
        _alarms(check)
        _goals(check)
        _dealsource(check)
        _cadence(check)
        _coachpick(check)
        _researchstats(check)
        _pacing(check)
        _integration(check)
    finally:
        kpi.override(None)
        fresh()
        restore(before)
        for k in added:
            registry.EXTRA.pop(k, None)
            policy.SPEND_BY_KIND.pop(k, None)
        policy.KINDS, policy.NO_PRESETS, sweep.REPORT_KINDS = saved_pol
        PRESETS.clear()
        PRESETS.update(saved_presets)
        config.DATA_DIR, config.MODE, config.TEAM_DIR = saved_cfg


